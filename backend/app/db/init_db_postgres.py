from app.db.connection import create_connection

CREATE_CITIES_TABLE = """
CREATE TABLE IF NOT EXISTS cities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE,
    name TEXT NOT NULL,
    country_code TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,

    UNIQUE(name, country_code),

    CHECK(latitude >= -90 AND latitude <= 90),
    CHECK(longitude >= -180 AND longitude <= 180)
)
"""

CREATE_HOURLY_WEATHER_TABLE = """
CREATE TABLE IF NOT EXISTS hourly_weather (
    city_id INTEGER NOT NULL,
    observed_at TEXT NOT NULL,

    temperature_2m DOUBLE PRECISION,
    precipitation DOUBLE PRECISION,
    cloud_cover DOUBLE PRECISION,
    sunshine_duration DOUBLE PRECISION,
    relative_humidity_2m DOUBLE PRECISION,
    wind_speed_10m DOUBLE PRECISION,
    wind_direction_10m DOUBLE PRECISION,
    wind_gusts_10m DOUBLE PRECISION,

    PRIMARY KEY (city_id, observed_at),

    FOREIGN KEY(city_id)
        REFERENCES cities(id)
        ON DELETE CASCADE
)
"""

CREATE_DAILY_AVERAGES_WEATHER_TABLE = """
CREATE TABLE IF NOT EXISTS daily_averages_weather (
    city_id INTEGER NOT NULL,
    observed_date TEXT NOT NULL,

    temperature_2m_mean DOUBLE PRECISION,
    temperature_2m_max DOUBLE PRECISION,
    temperature_2m_min DOUBLE PRECISION,
    apparent_temperature_mean DOUBLE PRECISION,
    precipitation_sum DOUBLE PRECISION,
    cloud_cover_mean DOUBLE PRECISION,
    sunshine_duration_sum DOUBLE PRECISION,
    relative_humidity_2m_mean DOUBLE PRECISION,
    wind_speed_10m_mean DOUBLE PRECISION,
    wind_direction_10m_dominant DOUBLE PRECISION,
    wind_gusts_10m_max DOUBLE PRECISION,

    PRIMARY KEY (city_id, observed_date),

    FOREIGN KEY(city_id)
        REFERENCES cities(id)
        ON DELETE CASCADE
)
"""

CREATE_WIND_ROSE_TABLE = """
CREATE TABLE IF NOT EXISTS wind_rose (
    city_id INTEGER NOT NULL,
    direction TEXT NOT NULL,
    frequency DOUBLE PRECISION NOT NULL,
    sample_count INTEGER NOT NULL,
    average_speed DOUBLE PRECISION,

    PRIMARY KEY (city_id, direction),

    FOREIGN KEY(city_id)
        REFERENCES cities(id)
        ON DELETE CASCADE
)
"""


def init_db() -> None:
    """Create PostgreSQL tables; existing table definitions are not migrated."""
    with create_connection() as connection:
        connection.execute(CREATE_CITIES_TABLE)
        connection.execute(CREATE_HOURLY_WEATHER_TABLE)
        connection.execute(CREATE_DAILY_AVERAGES_WEATHER_TABLE)
        connection.execute(CREATE_WIND_ROSE_TABLE)
